def dds_argb32(w, h, pixel):
    """An uncompressed A8R8G8B8 DDS (one mip). pixel(x, y) -> (r, g, b, a)."""
    hdr = bytearray(128)
    hdr[0:4] = b"DDS "
    struct.pack_into("<7I", hdr, 4, 124, 0x100F, h, w, w * 4, 0, 0)   # size, CAPS|HEIGHT|WIDTH|PITCH|PIXELFORMAT
    struct.pack_into("<8I", hdr, 76, 32, 0x41, 0, 32,                  # DDPF_RGB | DDPF_ALPHAPIXELS
                     0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    struct.pack_into("<I", hdr, 108, 0x1000)                           # DDSCAPS_TEXTURE
    px = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b, a = pixel(x, y)
            px += bytes((b, g, r, a))                                  # little-endian ARGB = B G R A
    return bytes(hdr) + bytes(px)


def checker(c0, c1, cell=16, edge=(20, 18, 14)):
    def px(x, y):
        on = ((x // cell) + (y // cell)) % 2
        r, g, b = c1 if on else c0
        if x % cell == 0 or y % cell == 0:          # a thin grout line between the tiles
            r, g, b = edge
        return r, g, b, 255
    return px


