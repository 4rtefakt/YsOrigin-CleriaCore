#!/usr/bin/env python3
"""Generate CleriaCore's sample mod(s) under samples/mods/ (build/shell_re/MODS.md §8).

Everything is drawn from scratch here: no game file is read or copied, so the output is ours to
commit. The sample is a reskin: two floor textures of the tower's S_10 rooms (the base floor,
e.g. S_1009) replaced by generated checkerboards.

    python tools/make_sample_mods.py            # (re)writes samples/mods/checker_floor/
    python tools/make_sample_mods.py --zip out  # also writes out/checker_floor.zip (a zip mod)

Install: copy samples/mods/checker_floor (or the zip) into the mods folder (F1 > Mods > Open mods
folder), turn it on in the Mods tab and restart.
"""
import os, struct, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "samples", "mods", "checker_floor")

MANIFEST = """\
; CleriaCore sample mod (generated by tools/make_sample_mods.py; build/shell_re/MODS.md)
[mod]
Id=sample.checker_floor
Name="Checker Floor"
Version=1.0.0
Author="CleriaCore"
Description="A reskin example: the floor of the tower's base rooms (S_10, e.g. the goddess statue room S_1009) becomes a gold / blue and a red / cream checkerboard. The textures are generated from scratch by tools/make_sample_mods.py."
Priority=0
ApiVersion=1
"""


def dds_argb32(w, h, pixel):
    """An uncompressed A8R8G8B8 DDS (one mip). pixel(x, y) -> (r, g, b, a)."""
    hdr = bytearray(128)
    hdr[0:4] = b"DDS "
    struct.pack_into("<7I", hdr, 4, 124, 0x100F, h, w, w * 4, 0, 0)   # size, CAPS|HEIGHT|WIDTH|PITCH|PIXELFORMAT
    struct.pack_into("<8I", hdr, 76, 32, 0x41, 0, 32,                  # DDPF_RGB | DDPF_ALPHAPIXELS
                     0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    struct.pack_into("<I", hdr, 108, 0x1000)                           # DDSCAPS_TEXTURE
    px = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b, a = pixel(x, y)
            px += bytes((b, g, r, a))                                  # little-endian ARGB = B G R A
    return bytes(hdr) + bytes(px)


def checker(c0, c1, cell=16, edge=(20, 18, 14)):
    def px(x, y):
        on = ((x // cell) + (y // cell)) % 2
        r, g, b = c1 if on else c0
        if x % cell == 0 or y % cell == 0:          # a thin grout line between the tiles
            r, g, b = edge
        return r, g, b, 255
    return px


def main():
    files = {
        "files/MAP/S_10/COMMON/H/10YUKA04.DDS": dds_argb32(64, 64, checker((214, 176, 62), (40, 70, 140))),
        "files/MAP/S_10/COMMON/H/10YUKA14.DDS": dds_argb32(64, 64, checker((200, 60, 50), (236, 230, 210))),
    }
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "mod.ini"), "w", newline="\r\n") as f:
        f.write(MANIFEST)
    for rel, data in files.items():
        p = os.path.join(OUT, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
    print("wrote", OUT)
    if "--zip" in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index("--zip") + 1])
        os.makedirs(out, exist_ok=True)
        z = os.path.join(out, "checker_floor.zip")
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.write(os.path.join(OUT, "mod.ini"), "checker_floor/mod.ini")
            for rel in files:
                zf.write(os.path.join(OUT, *rel.split("/")), "checker_floor/" + rel)
        print("wrote", z)


if __name__ == "__main__":
    main()
