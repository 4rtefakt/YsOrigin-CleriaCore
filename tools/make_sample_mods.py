def lantern(dim=False):
    """A 64x64 lantern icon: a gold frame and handle around a glowing amber glass, on transparency."""
    import math

    def px(x, y):
        cx, fx, fy = 31.5, x + 0.5, y + 0.5
        col = None
        # the handle ring on top
        d = math.hypot(fx - cx, fy - 13.0)
        if 6.0 <= d <= 8.5 and fy <= 14.0:
            col = (200, 160, 60)
        # the cap and the base (gold bars)
        if 14.0 <= fy <= 19.0 and abs(fx - cx) <= 13.0 - (19.0 - fy) * 0.8:
            col = (222, 180, 70)
        if 50.0 <= fy <= 55.0 and abs(fx - cx) <= 14.0:
            col = (200, 156, 58)
        # the glass: a warm glow, brightest at the flame
        if 19.0 < fy < 50.0 and abs(fx - cx) <= 11.0:
            g = max(0.0, 1.0 - math.hypot((fx - cx) / 11.0, (fy - 36.0) / 14.0))
            col = (int(150 + 105 * g), int(80 + 150 * g), int(30 + 120 * g * g))
            if abs(fx - cx) >= 10.0 or abs(fx - cx) <= 0.7 and g < 0.35:   # the frame's side posts / mid bar
                col = (190, 150, 55)
        # the flame
        if math.hypot((fx - cx) / 3.2, (fy - 37.0) / 6.0) <= 1.0:
            col = (255, 250, 210)
        if col is None:
            return 0, 0, 0, 0
        if dim:
            v = int(sum(col) / 3 * 0.45)
            col = (v, v, v)
        return col[0], col[1], col[2], 255
    return px


def write_tree(out, files):
    for rel, data in files.items():
        p = os.path.join(out, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        if isinstance(data, str):
            with open(p, "w", newline="\r\n") as f:
                f.write(data)
        else:
            with open(p, "wb") as f:
                f.write(data)


def chest_swap():
    files = dict(CHEST_SWAP_FILES)
    files["files/MENU/ICON/CS_LANTERN.DDS"] = dds_argb32(64, 64, lantern())
    files["files/MENU/ICON2/CS_LANTERNV.DDS"] = dds_argb32(64, 64, lantern(dim=True))
    write_tree(CHEST_SWAP, files)
    print("wrote", CHEST_SWAP)


