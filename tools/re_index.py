#!/usr/bin/env python3
"""Generate build/RE_INDEX.md — a navigable index of every RE doc.

Globs build/*_re/*.md, groups by subsystem, and pulls each doc's H1 title + first
prose sentence. Run after adding/changing RE docs: python tools/re_index.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
docs = sorted(glob.glob(os.path.join(ROOT, "build", "*_re", "*.md")))


def summary(path):
    title, desc = os.path.basename(path)[:-3], ""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.readlines()
    for ln in lines:
        s = ln.strip()
        if s.startswith("# "):
            title = s[2:].strip()
            break
    for ln in lines:
        s = ln.strip()
        if not s or s.startswith(("#", ">", "|", "-", "*", "`", "![")):
            continue
        s = re.sub(r"`([^`]*)`", r"\1", s)
        s = re.sub(r"\*\*([^*]*)\*\*", r"\1", s)
        desc = s.split(". ")[0][:150]
        break
    return title, desc


by_sys = {}
for d in docs:
    m = re.search(r"build[\\/]([^\\/]+)_re[\\/]", d.replace("\\", "/"))
    by_sys.setdefault(m.group(1) if m else "?", []).append(d)

out = ["# CleriaCore RE documentation index", "",
       f"{len(docs)} reverse-engineering docs across {len(by_sys)} subsystems. Coverage: "
       "`build/RE_COVERAGE.md`; gap map: `build/ROADMAP.md`; engine architecture: `build/arch_re/`. "
       "Auto-generated by `tools/re_index.py`.", ""]
for sysn in sorted(by_sys):
    out += [f"## {sysn}", ""]
    for d in sorted(by_sys[sysn]):
        rel = os.path.relpath(d, ROOT).replace("\\", "/")
        t, desc = summary(d)
        out.append(f"- [{t}]({rel}) — {desc}" if desc else f"- [{t}]({rel})")
    out.append("")

open(os.path.join(ROOT, "build", "RE_INDEX.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote build/RE_INDEX.md — {len(docs)} docs, {len(by_sys)} subsystems")
