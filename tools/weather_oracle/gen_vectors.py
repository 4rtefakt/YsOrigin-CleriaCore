# Generate apps/cleria-weathertest/oracle.inl: the retail update bodies (FUN_0058e7c0 /
# FUN_0058daa0) executed on the exe bytes by x86emu.py, per scenario: the shared xorshift state
# after every tick it changed, each FUN_00583d90 descriptor, the smoke's offset / child position.
#     python tools/weather_oracle/gen_vectors.py apps/cleria-weathertest/oracle.inl
# Needs the retail yso_win.exe (x86emu.EXE), pefile, capstone, numpy.
import sys
import oracle

SCEN = [
    # name, kind, cap, ticks, noise, alloc-fail-at, seed, eye, at
    ("ember", "ember", 180, 185, 0, (), [123456789, 362436069, 521288629, 916191069], (10.5, 20.25, -30.75), (2.0, 1.5, -4.0)),
    ("ember_noise", "ember", 180, 60, 1, (), [0x1234567, 0x89abcdef, 0x0badf00d, 0xdeadbeef], (-35.0, 12.0, 20.0), (-35.1, 1.0, 34.9)),
    ("ember_full", "ember", 180, 40, 0, (1,), [5, 6, 7, 8], (0.0, 10.0, -10.0), (0.0, 1.0, 0.0)),
    ("ember_short", "ember", 20, 25, 0, (), [77, 88, 99, 1010], (3.0, 9.0, -12.0), (0.5, 1.0, 0.25)),
    ("smoke", "smoke", 120, 125, 0, (), [123456789, 362436069, 521288629, 916191069], (10.5, 20.25, -30.75), (2.0, 1.5, -4.0)),
    ("smoke_noise_a", "smoke", 120, 8, 1, (), [0x1234567, 0x89abcdef, 0x0badf00d, 0xdeadbeef], (-35.0, 12.0, 20.0), (-35.1, 1.0, 34.9)),
    ("smoke_noise_b", "smoke", 120, 8, 1, (), [3, 21, 39, 93], (-35.0, 12.0, 20.0), (-35.1, 1.0, 34.9)),
    ("smoke_full", "smoke", 120, 6, 0, (1,), [5, 6, 7, 8], (0.0, 10.0, -10.0), (0.0, 1.0, 0.0)),
]

def u(v): return "0x%08xu" % (v & 0xffffffff)

out = []
out.append("// GENERATED by tools/weather_oracle/gen_vectors.py from the retail FUN_0058e7c0 / FUN_0058daa0 bytes")
out.append("// executed by an x86 interpreter (stubbed FUN_0040f700 / FUN_00583a00 / FUN_00583d90). Do not edit.")
out.append("struct OScen { const char* name; int smoke; std::uint32_t cap; int ticks; int noise; int fail_at;")
out.append("               std::uint32_t seed[4]; float eye[3], at[3]; int first, count; };")
out.append("struct OTick { int t; std::uint32_t rng[4]; int dead; int emit; std::uint32_t off[3], cpos[3]; };")
out.append("struct OEmit { std::uint32_t d[27]; };")
ticks, emits, scen = [], [], []
seen = set()
for name, kind, cap, n, noise, fail, seed, eye, at in SCEN:
    r = oracle.run(kind, cap, n, seed, eye, at, noise, fail)
    first = len(ticks)
    prev = list(seed); prev_dead = False
    for x in r:
        changed = x["rng"] != prev or x["emits"] or x["dead"] != prev_dead
        prev = x["rng"]; prev_dead = x["dead"]
        if not changed: continue
        ei = -1
        if x["emits"]:
            assert len(x["emits"]) == 1
            ei = len(emits); emits.append(x["emits"][0]["d"])
            if kind == "smoke" and noise: seen.add(x["emits"][0]["d"][3])
        off = x.get("off", [0, 0, 0]); cp = x.get("child_pos") or [0, 0, 0]
        ticks.append((x["t"], x["rng"], int(x["dead"]), ei, off, cp))
    scen.append((name, int(kind == "smoke"), cap, n, noise, fail[0] if fail else 0, seed, eye, at, first, len(ticks) - first))
print("smoke noise colours seen:", [hex(c) for c in seen], file=sys.stderr)
out.append("static const OScen kScen[] = {")
for s in scen:
    name, sm, cap, n, noise, fa, seed, eye, at, first, cnt = s
    out.append('    {"%s", %d, %du, %d, %d, %d, {%s}, {%sf, %sf, %sf}, {%sf, %sf, %sf}, %d, %d},' % (
        name, sm, cap, n, noise, fa, ", ".join(u(v) for v in seed), *[repr(float(v)) for v in eye], *[repr(float(v)) for v in at], first, cnt))
out.append("};")
out.append("static const OTick kTicks[] = {")
for t, rng, dead, ei, off, cp in ticks:
    out.append("    {%d, {%s}, %d, %d, {%s}, {%s}}," % (t, ", ".join(u(v) for v in rng), dead, ei,
               ", ".join(u(v) for v in off), ", ".join(u(v) for v in cp)))
out.append("};")
out.append("static const OEmit kEmits[] = {")
for d in emits:
    out.append("    {{%s}}," % ", ".join(u(v) for v in d))
out.append("};")
open(sys.argv[1], "w", newline="\r\n").write("\n".join(out) + "\n")
print(len(ticks), "ticks", len(emits), "emits", file=sys.stderr)
