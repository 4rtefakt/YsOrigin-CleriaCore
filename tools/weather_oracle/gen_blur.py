# Generate apps/cleria-weathertest/blur_oracle.inl: FireBlur's wave grid (WEATHER.md §5) on the exe's
# own bytes, run by x86emu.py:
#   FUN_005e44c0 (the renderer init's grid build, from FUN_005e2670): the 36 pretransformed vertices
#     at 0x7b251c (x, y, z, rhw, colour, u, v; stride 0x1c), their base copy at 0x7b290c, the phase
#     counters 0x7b2cfc / 0x7b2d8c, for a back buffer W x H and a copy texture TW x TH;
#   FUN_00427c90 (master update step 9) ticked with FireBlur(level, delta, strength) set and the draw
#     flag 0x7b2e1c raised before chosen ticks (the draw pass FUN_005fed30 sets it): 0x76a558,
#     0x7b249c, 0x7b2e1c and every vertex x / y after each tick. FUN_0041c510 (cos) is stubbed with
#     the CRT's float -> double -> cos -> float.
#     python tools/weather_oracle/gen_blur.py apps/cleria-weathertest/blur_oracle.inl
# Needs the retail yso_win.exe (x86emu.EXE), pefile, capstone, numpy.
import math, sys
import numpy as np
from x86emu import Emu, f32, bits32

GRID, BASE, CA, CB = 0x7b251c, 0x7b290c, 0x7b2cfc, 0x7b2d8c

def fresh():
    e = Emu(); e.r["esp"] = 0x00200000; e.wd(e.fs0, 0)
    for k in range(36 * 7 * 2): e.wd(GRID + 4 * k, 0)
    for k in range(72): e.wd(CA + 4 * k, 0)
    return e

def build(e, W, H, TW, TH):
    e.wd(0x765100, W); e.wd(0x765104, H)
    e.setf(0x7b2f00, TW); e.setf(0x7b2f04, TH)
    e.run(0x5e44c0)

def grid(e):
    return [[e.rd(GRID + 28 * i + 4 * k) for k in range(7)] for i in range(36)]

def cos_stub(em):     # FUN_0041c510: cvtss2sd, CRT cos, cvtsd2ss (xmm0 in, xmm0 out)
    x = float(np.float32(f32(em.xmm[0][0])))
    em.xmm[0] = [bits32(np.float32(math.cos(x))), 0, 0, 0]
    return 0

def tick(e):
    for a, v in ((0x74ab8f, 0), (0x74c0f0, 1), (0x74c0f1, 0)): e.wd(a, v, 1)
    for a in (0x76a550, 0x76a548, 0x76a5ac): e.wd(a, 0)
    e.wd(0x76a5b0, 0, 1)
    e.calls = {0x41c510: cos_stub}
    e.run(0x427c90)

def u(v): return "0x%08xu" % (v & 0xffffffff)

out = ["// GENERATED by tools/weather_oracle/gen_blur.py from the retail FUN_005e44c0 / FUN_00427c90 bytes",
       "// executed by an x86 interpreter (FUN_0041c510 = cos stubbed). Do not edit.",
       "struct BGrid { int w, h; float tw, th; std::uint32_t v[36][7]; std::int32_t a[36], b[36]; };",
       "struct BTick { int drawn_before; std::uint32_t level, out; int drawn_after; std::uint32_t xy[36][2]; };"]
grids = []
for W, H, TW, TH in ((1280, 720, 2048.0, 1024.0), (1024, 768, 1024.0, 1024.0), (1920, 1080, 2048.0, 2048.0)):
    e = fresh(); build(e, W, H, TW, TH)
    grids.append((W, H, TW, TH, grid(e), [e.rd(CA + 4 * i) for i in range(36)], [e.rd(CB + 4 * i) for i in range(36)]))
out.append("static const BGrid kBGrids[] = {")
for W, H, TW, TH, g, a, b in grids:
    out.append("    {%d, %d, %r, %r, {%s}, {%s}, {%s}}," % (W, H, TW, TH, ", ".join("{%s}" % ", ".join(u(x) for x in r) for r in g),
               ", ".join(str(np.int32(np.uint32(x))) for x in a), ", ".join(str(np.int32(np.uint32(x))) for x in b)))
out.append("};")

# The step scenario: 1280 x 720; FireBlur(1.0, -0.0025, 0.3) on tick 1; the draw flag raised before
# every tick except a few (no frame drawn between those ticks); 420 ticks (the level runs out at 400).
e = fresh(); build(e, 1280, 720, 2048.0, 1024.0)
e.setf(0x76a558, 1.0); e.setf(0x76a55c, -0.0025); e.setf(0x76a560, 0.3)
e.wd(0x7b2e1c, 0); e.wd(0x7b249c, 0)
SKIP = {1, 5, 6, 50, 399}
ticks = []
for t in range(1, 421):
    db = 0 if t in SKIP else 1
    e.wd(0x7b2e1c, db)
    tick(e)
    ticks.append((db, e.rd(0x76a558), e.rd(0x7b249c), e.rd(0x7b2e1c),
                  [(e.rd(GRID + 28 * i), e.rd(GRID + 28 * i + 4)) for i in range(36)]))
out.append("static const BTick kBTicks[] = {")
for db, lv, o, da, xy in ticks:
    out.append("    {%d, %s, %s, %d, {%s}}," % (db, u(lv), u(o), da, ", ".join("{%s, %s}" % (u(x), u(y)) for x, y in xy)))
out.append("};")
open(sys.argv[1], "w", newline="\r\n").write("\n".join(out) + "\n")
print(len(grids), "grids", len(ticks), "ticks", file=sys.stderr)
