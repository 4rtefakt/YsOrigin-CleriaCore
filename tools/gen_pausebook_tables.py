# Regenerate src/cleria/pausebook_tables.inc from yso_win.exe v1.1.1.0: the Topic page's entry
# tables, the manual page paths, the EN boss-description overrides, and the map overlay's
# record table and cloud mesh (build/menu_re/PAUSEBOOK_DRAW_TOPIC_MAP.md §2.2, §4.2, §5.1, §6).
# usage: python tools/gen_pausebook_tables.py
import os
import struct
import pefile

EXE = os.environ.get("YSO_EXE", r"D:\SteamLibrary\steamapps\common\Ys Origin\yso_win.exe")
OUT = "src/cleria/pausebook_tables.inc"
pe = pefile.PE(EXE, fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
img = pe.get_memory_mapped_image()


def u32(va): return struct.unpack_from('<I', img, va - base)[0]
def i32(va): return struct.unpack_from('<i', img, va - base)[0]
def f32(va): return struct.unpack_from('<f', img, va - base)[0]
def u16(va): return struct.unpack_from('<H', img, va - base)[0]


def cstr(va):
    b = img[va - base:va - base + 512]
    return b.split(b'\0')[0].decode('latin1')


def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\r', '\\r').replace('\n', '\\n') + '"'


EMPTY = 0x694c4c
out = ['// Generated by tools/gen_pausebook_tables.py from yso_win.exe v1.1.1.0 -- do not edit.', '']


def entries(name, va, n):
    out.append(f'// {va:#x}: {n} x 0x24 {{cast id, portrait, boss marker, HP, STR, EXP, LV, DEF, GOLD}}')
    out.append(f'constexpr TopicEntry {name}[{n}] = {{')
    for i in range(n):
        e = va + i * 0x24
        boss = u32(e + 8) != EMPTY
        stats = ', '.join(str(i32(e + 0x0c + 4 * k)) for k in range(6))
        p = cstr(u32(e + 4)).split('\\')[-1]
        out.append(f'    {{{u32(e)}, {lit(p)}, {str(boss).lower()}, {{{stats}}}}},')
    out.append('};')


entries('kTopicChars', 0x68d5d0, 28)
entries('kTopicMonsters', 0x68d9c0, 92)

out.append('')
out.append('// 0x68d504[char] -> 13 manual page paths (data\\image\\v_###.dds).')
out.append('constexpr const char* kManualPages[4][13] = {')
for c in range(4):
    t = u32(0x68d504 + 4 * c)
    names = [lit(cstr(u32(t + 4 * k)).split('\\')[-1]) for k in range(13)]
    out.append('    {' + ', '.join(names) + '},')
out.append('};')

out.append('')
out.append('// FUN_005bff40 language-1 overrides of the boss text block 1 (cast id -> string).')
ov = {0x7f: 0x6a6f38, 0x80: 0x6a6f34, 0x83: 0x6a6f30, 0x86: 0x6a6f2c, 0x87: 0x6a6f28, 0x89: 0x6a6f24,
      0x8a: 0x6a6f20, 0x8b: 0x6a6f1c, 0x8f: 0x6a6f18, 0x90: 0x6a6f14, 0x92: 0x6a6f10, 0x93: 0x6a6f0c,
      0x95: 0x6a6f08}
out.append('constexpr BossText kBossTextEn[13] = {')
for cid, p in ov.items():
    out.append(f'    {{{cid:#x}, {lit(cstr(u32(p)))}}},')
out.append('};')

out.append('')
out.append('// 0x701730: 22 x 0x28 {X, Y, X2, Y2, link[6]} (left/self/right, up/self/down).')
out.append('constexpr MapRec kMapRecs[22] = {')
for i in range(22):
    r = 0x701730 + i * 0x28
    links = ', '.join(str(i32(r + 0x10 + 4 * k)) for k in range(6))
    fl = lambda v: (f'{v:.6g}' if any(c in f'{v:.6g}' for c in '.e') else f'{v:.6g}.0') + 'f'
    out.append(f'    {{{fl(f32(r))}, {fl(f32(r + 4))}, {fl(f32(r + 8))}, {fl(f32(r + 12))}, {{{links}}}}},')
out.append('};')

out.append('')
out.append('// 0x6a7400: the cloud mesh index list (32 triangles over the 5x5 grid).')
idx = [u16(0x6a7400 + 2 * k) for k in range(96)]
out.append('constexpr std::uint16_t kCloudIdx[96] = {' + ', '.join(map(str, idx)) + '};')
out.append('')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', OUT)
